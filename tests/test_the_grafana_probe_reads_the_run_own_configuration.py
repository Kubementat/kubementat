"""The Grafana probe has to log in with the run's own credentials, to an address it can reach.

It used to send `-u admin:<something>` to `<svc>.<ns>.svc.cluster.local`, taking the password
from the team's encrypted file. Three things were wrong at once, and the lane only showed the
last one: `admin` is a user no configuration names, the team file declares neither of the
Grafana admin keys, and a cluster-internal service name does not resolve on the node the probe
runs on — so the report read `000`, which is neither an accepted nor a rejected credential.

These tests run the stage against a fake guest, so each half is attributable: the credential,
the address, the namespace, and what the assert says when the account the run *exported* is not
the account that exists — and whether the create row is evidence at all. The two
asserts that ask that are `grafana-account-rows-declared` (before the command, because an
environment that declares no accounts has nothing to create) and `grafana-account-created` (after
it, because `created.ok` is not evidence of an account). Both directions are asserted here, so
neither can be satisfied by an assert that always says the same thing.
"""

import json
import shlex

import pytest
from e2e_probe_stub import Answer, FakeArtifacts, FakeGuest, Recording, load_harness, shown

stages = load_harness()

CONFIGURED_USER = "grafadmin"          # what `static.encrypted.json` ships and installs
ADMIN_PASSWORD = "not-a-real-password"  # generated by `initialize`, readable from the file
NAMESPACE = "grafana"
CLUSTER_IP = "10.43.71.20"

# The one row `GRAFANA_USERS` has to have for this row to be evidence of anything. The stage seeds
# it itself and then reads it back, so the fake's config declares exactly that row -- both
# halves of "did anything actually happen" are visible without a cluster.
DECLARED_EMAIL = "kmt-e2e-account@example.invalid"
DECLARED_ROW = json.dumps([{"email": DECLARED_EMAIL, "name": "kmt-e2e lane account",
                             "password": "not-a-password"}])


@pytest.fixture(scope="module")
def harness():
    return stages


@pytest.fixture
def runner():
    """The stage, its fake guest, and everything it asserted."""
    guest = FakeGuest()
    recording = Recording()
    lane = stages.config.LANES["full"]
    options = type("Options", (), {"env": {}, "stage_timeout": lambda name, seconds: seconds})
    instance = stages.LaneRunner(lane, options, FakeArtifacts(), None, {}, recording, lambda message: None)
    instance.guest = guest
    instance.cluster = stages.asserts.Cluster(guest)
    instance.stage = "05-features"
    instance._recording = recording
    return instance


def given_a_running_grafana(runner, namespace=NAMESPACE, cluster_ip=CLUSTER_IP,
                            installed_user=CONFIGURED_USER, code="200",
                            declared=DECLARED_ROW, roster=True, duplicated=False,
                            rerun_creates=False, rerun_output=None, rerun_exit=0):
    """A lane where grafana exists, is reachable, and answers the API with `code`.

    The two files are deliberately separated: the *plain* environment config holds the
    namespace, the *encrypted* one holds the admin pair and the account rows. A probe that reads
    the team's file finds nothing, so the rules here only answer the paths that actually have
    the keys.

    A login is answered per user: the configured one gets `code`, anybody else's gets `401`.
    One blanket answer would let the exported-account test report `200` for a user that does not
    exist, which is not what a cluster does and would make the harness's own detail lie.

    `declared` is what `GRAFANA_USERS` says (`""` for an environment that declares nothing),
    `roster` is whether `/api/org/users` has that address in it, `duplicated` gives the address
    twice, and `rerun_creates` makes the second run create again -- the three dials that make the
    create and the rerun honest rather than merely executed.
    """
    guest = runner.guest
    guest.state.setdefault("creates", 0)

    def login(command):
        requested = command.split("-u ")[-1].strip().strip("'").split(":")[0]
        if requested != installed_user:
            return Answer(0, '{"message":"Unauthorized"}' + "401", "")
        # `/api/org/users` answers with a bare array of org-member rows -- the shape the full
        # lane captured (`orgId/userId/uid/email/login/role`). The stub used to wrap the rows in
        # `{"users": ..., "totalCount": ...}`, which is what `/api/users/search` answers and
        # `/api/org/users` never did: that fiction is how the harness's roster parser survived
        # reading a shape no grafana sends.
        rows = [{"orgId": 1, "userId": 7, "uid": "eg2sf6zbajjlsa", "email": DECLARED_EMAIL,
                 "login": DECLARED_EMAIL, "name": "kmt-e2e lane account", "role": "Viewer"}]
        if not roster:
            rows = []
        if roster and duplicated:
            rows = rows + [{"orgId": 1, "userId": 8, "uid": "dg2sf6zbajjlsa",
                            "email": DECLARED_EMAIL, "login": DECLARED_EMAIL,
                            "name": "the same address twice", "role": "Viewer"}]
        return Answer(0, json.dumps(rows) + code, "")

    def create(command):
        # One answer per invocation, because the stage runs the command twice on purpose and the
        # second answer is the whole content of the idempotency row.
        guest.state["creates"] += 1
        if guest.state["creates"] == 1:
            return Answer(0, "created grafana account %s (user 7, kmt-e2e lane account)\n" % DECLARED_EMAIL, "")
        if rerun_output is not None:
            return Answer(rerun_exit, rerun_output, "")
        if not rerun_creates:
            return Answer(0, "grafana account %s already exists (user 7); nothing changed and no "
                             "password was applied\n" % DECLARED_EMAIL, "")
        return Answer(0, "created grafana account %s (user 8, kmt-e2e lane account)\n" % DECLARED_EMAIL, "")

    guest.respond("create_grafana_accounts.sh", Answer(0, "creating grafana accounts\n", ""))
    guest.respond("kmt users create-grafana-accounts", create)
    guest.respond("static.encrypted.json", lambda command: installed_user
                  if "GRAFANA_ADMIN_USER" in command else
                  (declared if "GRAFANA_USERS" in command else ADMIN_PASSWORD))
    # The namespace is answered, not declared: `config init` writes no template and
    # `constants.DEFAULT_NAMESPACES` carries `grafana`, so the layer the stage would have grepped
    # holds nothing. The fake answers the verb, in the verb's shape, because that is the read the
    # stage now makes and the tag is part of the answer.
    guest.respond("config show", shown(GRAFANA_DEPLOYMENT_NAMESPACE=namespace))
    guest.respond("kubectl get svc", lambda command: (
        '{"items": [{"metadata": {"name": "grafana"}, '
        '"spec": {"clusterIP": "%s", "ports": [{"port": 3000}]}}]}' % cluster_ip
        if cluster_ip else
        '{"items": [{"metadata": {"name": "grafana"}, '
        '"spec": {"clusterIP": "None", "ports": [{"port": 3000}]}}]}'))
    guest.respond("curl ", login)
    return guest


def test_the_probe_logs_in_as_the_admin_the_configuration_names(runner):
    given_a_running_grafana(runner)

    runner.feature_grafana_accounts()

    commands = runner.guest.commands_matching("curl ")
    assert commands, "the API check is a real login attempt, not a config read"
    assert "-u %s" % shlex.quote("%s:%s" % (CONFIGURED_USER, ADMIN_PASSWORD)) in commands[0], commands[0]
    assert "-u %s" % shlex.quote("admin:%s" % ADMIN_PASSWORD) not in commands[0], \
        "the hardcoded `admin` is a user no configuration names: %s" % commands[0]
    assert runner._recording.passed("assert:grafana-api-readable")


def test_the_credentials_come_from_the_encrypted_environment_file_never_the_teams(runner):
    given_a_running_grafana(runner)

    runner.feature_grafana_accounts()

    reads = " ".join(runner.guest.commands_matching("jq -r"))
    assert "platform_config/%s/static.encrypted.json" % stages.config.ENVIRONMENT in reads
    assert "%s/static.encrypted.json" % stages.config.TEAM not in reads, \
        "the team file declares neither key, so reading it is how the probe lost the password"


def test_the_probe_opens_a_cluster_ip_because_a_service_name_is_not_reachable_from_the_node(runner):
    given_a_running_grafana(runner)

    runner.feature_grafana_accounts()

    command = runner.guest.commands_matching("curl ")[0]
    assert "http://%s:3000/api/org/users" % CLUSTER_IP in command, command
    assert "svc.cluster.local" not in command, \
        "a pod-style name answers 000 from the node and tells you nothing about the credential"


def test_a_headless_service_is_reported_as_unreachable_rather_than_as_a_bad_credential(runner):
    given_a_running_grafana(runner, cluster_ip=None)

    runner.feature_grafana_accounts()

    entry = runner._recording.entry("assert:grafana-api-readable")
    assert entry["passed"] is False
    assert "ClusterIP" in entry["detail"] and "cluster.local" not in entry["detail"], entry["detail"]


def test_the_namespace_the_probe_asks_in_comes_from_the_environment_config(runner, monkeypatch):
    # The namespace is read from the configuration now; this is what stops it drifting back to a literal.
    given_a_running_grafana(runner)
    monkeypatch.setattr(stages.LaneRunner, "_environment_config_value",
                        lambda self, field, filename="static.json":
                        "observability" if field == "GRAFANA_DEPLOYMENT_NAMESPACE" else
                        (CONFIGURED_USER if field == "GRAFANA_ADMIN_USER" else ADMIN_PASSWORD))

    runner.feature_grafana_accounts()

    assert runner.guest.saw("kubectl get svc", "-n observability"), runner.guest.commands
    assert "observability" in runner.guest.commands_matching("kubectl get svc")[0]


def test_the_suite_never_logs_in_as_a_name_the_configuration_does_not_name(runner):
    # The lane used to export `GRAFANA_ADMIN_USER=kmt-e2e-admin`, on the template's advice, and then
    # asked whether that export had reached the install. It cannot: `static.encrypted.json` is the
    # source of truth and kubementat exports that pair itself, so the exported name is not a second
    # authority and the assert that measured it has gone. What remains is the part that is about the
    # probe and not about the lane: *which pair* every login carries -- not how many logins there are,
    # which went from one to two the day the roster started being read after the rerun as well as after
    # the create.
    given_a_running_grafana(runner)

    runner.feature_grafana_accounts()

    logins = runner.guest.commands_matching("curl ")
    assert len(logins) == 2, logins
    pair = shlex.quote("%s:%s" % (CONFIGURED_USER, ADMIN_PASSWORD))
    assert all(pair in command for command in logins), \
        "a login the configured file does not name is a credential nobody chose: %s" % logins
    assert all("-u admin:" not in command for command in logins), \
        "the hardcoded `admin` is a user no configuration names: %s" % logins
    assert not runner._recording.named("assert:exported-grafana-admin-user-reaches-the-install"), \
        "a resolved design decision does not belong in a lane that still has to be able to fail on it"


def test_a_401_stays_red_when_the_credentials_are_right_but_the_account_is_not(runner):
    given_a_running_grafana(runner, code="401")

    runner.feature_grafana_accounts()

    assert runner._recording.passed("assert:grafana-api-readable") is False
    assert "401" in runner._recording.detail("assert:grafana-api-readable")


def test_an_environment_that_declares_no_accounts_is_not_a_green_row(runner):
    """The vacuity this row was born with, on the harness side of it.

    A create that runs and creates nothing is green twice over if nobody looks: once when the
    address was wrong, and once again if `GRAFANA_USERS` names nobody. So the count is asserted
    before the command runs, and the failure says that the vacuity would be in the configuration
    rather than in the product — which is the difference between a red row and an unmeasured one.
    """
    given_a_running_grafana(runner, declared="")

    runner.feature_grafana_accounts()

    assert runner._recording.passed("assert:grafana-account-rows-declared") is False
    assert "GRAFANA_USERS" in runner._recording.detail("assert:grafana-account-rows-declared")


def test_a_create_that_succeeded_still_has_to_have_created_the_account_it_was_asked_for(
        runner):
    """`created.ok` is not the answer; the roster is.

    The command can exit 0 for the wrong reason exactly once more — grafana accepted a create that
    landed nowhere, or the address it resolved to was not this grafana. The declared address
    appearing in `/api/org/users` is the only evidence that closes that, and it is the half no
    unit test over a fake transport can supply.
    """
    given_a_running_grafana(runner, roster=False)

    runner.feature_grafana_accounts()

    assert runner._recording.passed("assert:grafana-account-created") is False
    assert DECLARED_EMAIL in runner._recording.detail("assert:grafana-account-created")


def test_the_account_the_command_was_asked_for_is_the_account_the_roster_shows(runner):
    """The same pair, answered honestly: declared, created, present.

    Without this one the two asserts above could be satisfied by an assert that always says
    "missing". Both directions have to be able to move.
    """
    given_a_running_grafana(runner)

    runner.feature_grafana_accounts()

    assert runner._recording.passed("assert:grafana-account-rows-declared")
    assert runner._recording.passed("assert:grafana-account-created")


def test_the_lane_seeds_its_one_row_before_it_asks_grafana_for_anything(runner):
    """The row the lane reports is a row it wrote, and it wrote it first.

    Both halves matter. `create-grafana-accounts` answers "declares no accounts, nothing was
    created" and exits 0, so a config that declares nobody is a green lane that executed nothing;
    that is why the harness puts the row in the environment's `static.encrypted.json` before the
    command runs rather than asserting a count it never wrote. And the write went through the verb:
    the row is a staged **answers document** whose path is the argument, which is what the
    single-writer rule and the password rule both need. The document's path is therefore what an
    order assert can see, and the generated password is what it must not see -- a password in a
    command line is a password in every `ps`, every ssh log line and every captured command.
    """
    given_a_running_grafana(runner)

    runner.feature_grafana_accounts()

    assert runner._recording.passed("assert:grafana-account-row-seeded"), \
        runner._recording.detail("assert:grafana-account-row-seeded")
    commands = runner.guest.commands
    document = stages.config.GRAFANA_ANSWER_DOCUMENT
    staged = min(i for i, command in enumerate(commands) if document in command)
    create = min(i for i, command in enumerate(commands) if "create-grafana-accounts" in command)
    assert staged < create, "the seed landed after the command it is supposed to declare"
    secret = json.loads(runner.guest.files[document])["GRAFANA_USERS"][0]["password"]
    assert secret and secret not in " ".join(commands), \
        "the run's password travelled in a command line, where every log catches it"
    assert "REPLACEME" not in json.dumps(runner.guest.files), "the lane seeded a placeholder, not a row"


def test_a_second_run_that_makes_the_account_a_second_time_is_red(runner):
    """The pair that makes the seeded row worth having, in the direction that can only be seen twice.

    One run cannot tell an idempotent create from a create that ran twice. The harness runs the
    command twice on purpose, so this row says what the roster says about the address afterwards:
    a second user with the same address is a duplicate, not an account.
    """
    given_a_running_grafana(runner, rerun_creates=True)

    runner.feature_grafana_accounts()

    assert runner._recording.passed("assert:grafana-account-created"), \
        "the first run still has to have made the account, or the rerun is comparing nothing"
    assert runner._recording.passed("assert:grafana-account-rerun-confirms-existing") is False
    assert DECLARED_EMAIL in runner._recording.detail("assert:grafana-account-rerun-confirms-existing")


def test_a_second_run_that_confirms_the_account_it_found_is_the_green_side(runner):
    """The other side of the same assert, so it cannot be satisfied by always saying "duplicate".

    A rerun that reports the already-exists case and changes nothing is the whole point of running
    it; a row that only knows how to fail would be a different kind of vacuous.
    """
    given_a_running_grafana(runner)

    runner.feature_grafana_accounts()

    assert runner._recording.passed("assert:grafana-account-rerun-confirms-existing"), \
        runner._recording.detail("assert:grafana-account-rerun-confirms-existing")
    assert runner.guest.commands_matching("create-grafana-accounts"), \
        "the command was not run twice, so nothing was confirmed"


def test_a_roster_that_holds_the_address_twice_is_a_duplicate_however_often_the_command_says_ok(
        runner):
    """The duplicate the command's own report cannot see.

    `ensure_account` asks grafana's directory for the address and stops when it finds one, so a
    second account hiding behind the same email only shows in the roster. This is where that goes
    red even when both runs reported success, which is the reason the row reads the roster after
    the rerun and not just the rerun's output.
    """
    given_a_running_grafana(runner, duplicated=True)

    runner.feature_grafana_accounts()

    assert runner._recording.passed("assert:grafana-account-rerun-confirms-existing") is False
    assert "duplicate" in runner._recording.detail("assert:grafana-account-rerun-confirms-existing")


def test_the_second_run_that_did_not_confirm_anything_is_red(runner):
    """The third way this row fails: a rerun that neither creates nor confirms.

    `created=False` and a silent stdout are not the same statement, and the code's own sentence
    for the case is what the row asserts on. A run that changes nothing and says nothing about the
    address cannot be told apart from one that confirmed it without reading its report.
    """
    given_a_running_grafana(runner, rerun_output="grafana accounts considered\n")

    runner.feature_grafana_accounts()

    assert runner._recording.passed("assert:grafana-account-rerun-confirms-existing") is False


def test_the_config_is_read_back_compactly_because_a_pretty_printed_list_is_not_several_lines(
        runner):
    """The vacuity that hid a *declared* row: `jq -r` answers a list of objects over many lines.

    `GRAFANA_USERS` is a list, and a line-by-line parse of a pretty-printed list finds nothing to
    parse, so a config that declared several accounts read as declaring none -- which is how a row
    that somebody had seeded came to be reported as "declares no rows". The read therefore asks
    for one value per line (`jq -c`), and this is what keeps it from drifting back to `-r`.
    """
    given_a_running_grafana(runner)

    runner._grafana_user_emails()

    reads = " ".join(runner.guest.commands_matching("GRAFANA_USERS"))
    assert "jq -c" in reads, reads
    assert "jq -r" not in reads, "a raw read of a list prints one key per line: %s" % reads
